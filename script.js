const papersContainer = document.getElementById("papersContainer");
const searchInput = document.getElementById("searchInput");
const subjectFilter = document.getElementById("subjectFilter");
const yearFilter = document.getElementById("yearFilter");
const noResults = document.getElementById("noResults");

// Display question paper cards
function displayPapers() {
    const searchText = searchInput.value.trim().toLowerCase();
    const selectedSubject = subjectFilter.value;
    const selectedYear = yearFilter.value;

    const filteredPapers = papers.filter((paper) => {
        const matchesSearch =
            paper.subject.toLowerCase().includes(searchText) ||
            String(paper.year).includes(searchText);

        const matchesSubject =
            selectedSubject === "all" ||
            paper.subject === selectedSubject;

        const matchesYear =
            selectedYear === "all" ||
            String(paper.year) === selectedYear;

        return matchesSearch && matchesSubject && matchesYear;
    });

    papersContainer.innerHTML = "";

    filteredPapers.forEach((paper) => {
        const card = document.createElement("article");
        card.className = "paper-card";

        const icon = document.createElement("div");
        icon.className = "paper-icon";
        icon.textContent = "📄";

        const title = document.createElement("h3");
        title.textContent = paper.subject;

        const board = document.createElement("p");
        board.textContent = "UP Board • Class 12";

        const year = document.createElement("p");
        year.textContent = `Year: ${paper.year}`;

        card.append(icon, title, board, year);

        const button = document.createElement("a");
        button.className = "paper-button";
        button.textContent = "View / Download PDF";
        button.href = paper.pdf;
        button.target = "_blank";
        button.rel = "noopener noreferrer";

        card.appendChild(button);
        papersContainer.appendChild(card);
    });

    noResults.hidden = filteredPapers.length > 0;

    if (filteredPapers.length === 0) {
        noResults.textContent =
            papers.length === 0
                ? "Question papers will appear here when PDFs are added."
                : "No question papers found. Try another search.";
    }
}

// Listen for user actions
searchInput.addEventListener("input", displayPapers);
subjectFilter.addEventListener("change", displayPapers);
yearFilter.addEventListener("change", displayPapers);

// Show papers when the page loads
displayPapers();